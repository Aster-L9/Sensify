"""
Schema migration for Sprint 2 (spec §7).

The project has no migration tool. When the database is not at SCHEMA_VERSION,
the file is backed up, user accounts are kept, and every other table is rebuilt
(the demo data is regenerated by the seed). A database already at
SCHEMA_VERSION is left untouched.

Version 2 and 3 databases are upgraded in place: v2 -> v3 rebuilds the incident
table; v3 -> v4 adds run playback columns (pause/reset) and lets an analysis
result have no trust score (insufficient evidence). Runs, results and users are kept.
"""
import shutil
from datetime import datetime
from pathlib import Path

from sqlalchemy import inspect, text
from sqlalchemy.engine import Engine

from app.database import Base
from app.models import Meta, User

SCHEMA_VERSION = 4

_USER_COLUMNS = ("id", "username", "email", "hashed_password", "role", "is_active", "created_at", "last_login")


def _current_version(engine: Engine) -> str | None:
    if "meta" not in inspect(engine).get_table_names():
        return None
    with engine.connect() as conn:
        return conn.execute(text("SELECT value FROM meta WHERE key = 'schema_version'")).scalar()


def _backup(engine: Engine) -> None:
    db_file = engine.url.database
    if not db_file or not Path(db_file).exists():
        return
    target = Path(f"{db_file}.sprint1.bak")
    if target.exists():
        target = Path(f"{db_file}.sprint1.{datetime.now():%Y%m%d%H%M%S}.bak")
    shutil.copy2(db_file, target)


def _as_datetime(value):
    if value is None or isinstance(value, datetime):
        return value
    return datetime.fromisoformat(str(value))


def _saved_users(engine: Engine) -> list[dict]:
    if "users" not in inspect(engine).get_table_names():
        return []
    with engine.connect() as conn:
        rows = conn.execute(text(f"SELECT {', '.join(_USER_COLUMNS)} FROM users")).mappings().all()
    return [
        {**row, "is_active": bool(row["is_active"]), "created_at": _as_datetime(row["created_at"]),
         "last_login": _as_datetime(row["last_login"])}
        for row in rows
    ]


def _upgrade_v3_to_v4(engine: Engine) -> None:
    columns = {c["name"] for c in inspect(engine).get_columns("runs")}
    with engine.begin() as conn:
        if "paused_at" not in columns:
            conn.execute(text('ALTER TABLE "runs" ADD COLUMN paused_at DATETIME'))
        if "paused_seconds" not in columns:
            conn.execute(text('ALTER TABLE "runs" ADD COLUMN paused_seconds FLOAT NOT NULL DEFAULT 0'))
    trust = next(c for c in inspect(engine).get_columns("analysis_results") if c["name"] == "trust_score")
    if trust["nullable"]:
        return
    # SQLite cannot relax NOT NULL in place: rebuild the table and copy every row across.
    indexes = [ix["name"] for ix in inspect(engine).get_indexes("analysis_results")]
    with engine.begin() as conn:
        for name in indexes:
            conn.execute(text(f'DROP INDEX IF EXISTS "{name}"'))
        conn.execute(text('ALTER TABLE "analysis_results" RENAME TO "analysis_results_v3"'))
    Base.metadata.tables["analysis_results"].create(engine)
    names = ", ".join(c.name for c in Base.metadata.tables["analysis_results"].columns)
    with engine.begin() as conn:
        conn.execute(text(f'INSERT INTO "analysis_results" ({names}) SELECT {names} FROM "analysis_results_v3"'))
        conn.execute(text('DROP TABLE "analysis_results_v3"'))


def migrate_if_needed(engine: Engine) -> bool:
    """Bring the database to SCHEMA_VERSION. Returns True when tables were (re)built."""
    version = _current_version(engine)
    if version == str(SCHEMA_VERSION):
        return False

    if version in ("2", "3"):
        if version == "2":  # additive v2 -> v3: only the incident tables change
            with engine.begin() as conn:
                conn.execute(text('DROP TABLE IF EXISTS "incidents"'))
            Base.metadata.create_all(engine)
        _upgrade_v3_to_v4(engine)
        with engine.begin() as conn:
            conn.execute(text("UPDATE meta SET value = :v WHERE key = 'schema_version'"), {"v": str(SCHEMA_VERSION)})
        return True

    tables = inspect(engine).get_table_names()
    users = []
    if tables:
        _backup(engine)
        users = _saved_users(engine)
        with engine.begin() as conn:
            conn.execute(text("PRAGMA foreign_keys = OFF"))
            for table in tables:
                conn.execute(text(f'DROP TABLE IF EXISTS "{table}"'))

    Base.metadata.create_all(engine)
    with engine.begin() as conn:
        if users:
            conn.execute(User.__table__.insert(), users)
        conn.execute(Meta.__table__.insert(), [{"key": "schema_version", "value": str(SCHEMA_VERSION)}])
    return True
